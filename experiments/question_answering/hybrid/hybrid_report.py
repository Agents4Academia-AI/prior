#!/usr/bin/env python3
"""Render RESULTS_HYBRID.md from the pilot's answers and judgements. FREE.

Generated, never hand-maintained — same contract as ../report.py, for the same
reason: a hand-written results file drifts from its data and nobody notices until
someone quotes the stale number.

The five predictions in PLAN_HYBRID.md §4 are scored MECHANICALLY here, against
the thresholds as written, and printed pass or fail without editorialising.
Registering predictions and then grading them by eye is how a pre-registration
quietly becomes a post-hoc narrative.

  python hybrid_report.py                 # -> RESULTS_HYBRID.md
  python hybrid_report.py --out -         # stdout
"""
from __future__ import annotations

import argparse
import collections
import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PARENT = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(PARENT))
sys.path.insert(0, str(PARENT.parent / "graph_vs_web_ideation"))

import routing                                                       # noqa: E402
from graph_tools import GraphAtlas                                   # noqa: E402

ANSWERS = HERE / "out" / "answers.jsonl"
JUDGEMENTS = HERE / "out" / "judgements.jsonl"
PARENT_ANSWERS = PARENT / "out" / "answers.jsonl"
ROLES = ("hybrid_directed", "hybrid_free", "incumbent")
AXES = ("groundedness", "correctness", "usefulness")
LABEL = {"hybrid_directed": "HYBRID · directed (atlas-first, browser on trigger)",
         "hybrid_free": "HYBRID · hands-off (both, no policy)",
         "incumbent": "INCUMBENT (the three-arm winner)"}

# the parent's graph-arm mean payload, for prediction 4
PARENT_GRAPH_PAYLOAD = 24_533

# The three questions the predictions were REGISTERED over. q03 was added after
# the first batch (PLAN_HYBRID.md §8), so it is reported alongside but is not
# allowed to move a registered prediction's verdict either way.
REGISTERED_QIDS = ("q01", "q04", "q06")


def _read(p: Path) -> list[dict]:
    if not p.exists():
        return []
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]


def mean(xs):
    xs = [x for x in xs if x is not None]
    return st.mean(xs) if xs else None


def fmt(x, n=2):
    return "—" if x is None else f"{x:.{n}f}"


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, ValueError):
        pass
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(HERE / "RESULTS_HYBRID.md"))
    args = ap.parse_args()

    ans = _read(ANSWERS)
    jud = _read(JUDGEMENTS)
    if not jud:
        sys.exit("no judgements yet — run hybrid_gen.py then hybrid_judge.py.")

    parent = {(r["question_id"], r["arm"]): r for r in _read(PARENT_ANSWERS)}
    by_q: dict[str, list[dict]] = collections.defaultdict(list)
    for r in jud:
        by_q[r["question_id"]].append(r)
    qids = sorted(by_q)
    arow = {(r["question_id"], r["arm"]): r for r in ans}

    atlas = GraphAtlas()
    route = {(r["question_id"], r["arm"]): routing.analyse(r, atlas)
             for r in ans if r.get("answer")}

    L: list[str] = []
    A = L.append

    A("# Hybrid pilot — atlas + browser\n")
    A("**Generated by `hybrid_report.py`. Do not edit by hand.**\n")
    A("An add-on to the three-arm experiment, not a revision of it. Design and "
      "registered predictions: [`PLAN_HYBRID.md`](PLAN_HYBRID.md). The parent "
      "result is unchanged and lives in [`../RESULTS.md`](../RESULTS.md).\n")
    A(f"{len(qids)} question(s) · {len(jud)} judgements · "
      f"{len(set(r['run'] for r in jud))} repeat(s) per question\n")

    # ── headline ────────────────────────────────────────────────────────────
    A("## Headline\n")
    A("| | " + " | ".join(LABEL[r] for r in ROLES) + " |")
    A("|---|" + "---|" * len(ROLES))
    for ax in AXES:
        A(f"| mean {ax} | "
          + " | ".join(fmt(mean(r[f"{a}_{ax}"] for r in jud)) for a in ROLES) + " |")
    wins = collections.Counter(r["best_answer"] for r in jud)
    A("| judgements won | "
      + " | ".join(str(wins.get(a, 0)) for a in ROLES) + f" | ")
    A(f"\n*{len(jud)} judgements over {len(qids)} question(s). "
      "With three questions these means sit inside the judge's own run-to-run "
      "spread — read the routing section, not the scoreboard.*\n")

    # ── predictions, scored mechanically ────────────────────────────────────
    A("## Registered predictions vs. outcome\n")
    A("Scored against the thresholds exactly as written in "
      "[`PLAN_HYBRID.md` §4](PLAN_HYBRID.md#4-predictions--registered-before-the-run), "
      "before any of these numbers existed.\n")
    A("| # | prediction | outcome | |")
    A("|---|---|---|---|")

    def qmean(qid, role, ax):
        return mean(r[f"{role}_{ax}"] for r in by_q.get(qid, []))

    def verdict(ok):
        return "**HELD**" if ok else ("**MISSED**" if ok is False else "n/a")

    # P1 — q06 correctness
    p1 = None
    if "q06" in by_q:
        d, inc = qmean("q06", "hybrid_directed", "correctness"), \
            qmean("q06", "incumbent", "correctness")
        if d is not None and inc is not None:
            p1 = (d - inc) >= 2
            A(f"| 1 | directed beats the incumbent on q06 correctness by ≥2 | "
              f"{fmt(d,1)} vs {fmt(inc,1)} = **{d-inc:+.1f}** | {verdict(p1)} |")
    if p1 is None:
        A("| 1 | directed beats the incumbent on q06 correctness by ≥2 | q06 not run | n/a |")

    # P2 — no regression on q01/q04
    bits, p2 = [], True
    for qid in ("q01", "q04"):
        if qid in by_q:
            d, inc = qmean(qid, "hybrid_directed", "groundedness"), \
                qmean(qid, "incumbent", "groundedness")
            if d is not None and inc is not None:
                bits.append(f"{qid} {d-inc:+.1f}")
                p2 = p2 and abs(d - inc) <= 1
    A(f"| 2 | directed does not regress on q01/q04 (groundedness within 1) | "
      f"{', '.join(bits) or '—'} | {verdict(p2 if bits else None)} |")

    # P3 — hands-off opens with the web. Scored on the REGISTERED three only;
    # any later addition is shown in brackets and excluded from the verdict.
    opens = [(qid, route[(qid, 'hybrid_free')]["first_tool"])
             for qid in qids if (qid, "hybrid_free") in route]
    reg = [(q, t) for q, t in opens if q in REGISTERED_QIDS]
    extra = [(q, t) for q, t in opens if q not in REGISTERED_QIDS]
    n_web_open = sum(1 for _, t in reg if t in routing.WEB_TOOLS)
    p3 = n_web_open >= 2 if reg else None
    A(f"| 3 | hands-off opens with a web search on ≥2 of 3 | "
      f"**{n_web_open} of {len(reg)}** ("
      + ", ".join(f"{q}:`{t}`" for q, t in reg) + ")"
      + (f" · added later: " + ", ".join(f"{q}:`{t}`" for q, t in extra)
         if extra else "")
      + f" | {verdict(p3)} |")

    # P4 — payload goes up
    pays = {a: mean(r["payload_chars"] for r in ans if r["arm"] == a)
            for a in ("hybrid_directed", "hybrid_free")}
    p4 = all(v is not None and v > PARENT_GRAPH_PAYLOAD for v in pays.values()) \
        if any(pays.values()) else None
    A(f"| 4 | both hybrids pull more payload than the graph arm "
      f"({PARENT_GRAPH_PAYLOAD:,} ch) | "
      + ", ".join(f"{a.split('_')[1]} {fmt(v,0)}" for a, v in pays.items())
      + f" | {verdict(p4)} |")

    # P5 — groundedness gain stays inside noise
    gains, p5 = [], True
    for qid in ("q01", "q04"):
        if qid in by_q:
            d, inc = qmean(qid, "hybrid_directed", "groundedness"), \
                qmean(qid, "incumbent", "groundedness")
            if d is not None and inc is not None:
                gains.append(f"{qid} {d-inc:+.1f}")
                p5 = p5 and (d - inc) < 1
    A(f"| 5 | groundedness *gain* on q01/q04 does not clear judge noise (<1) | "
      f"{', '.join(gains) or '—'} | {verdict(p5 if gains else None)} |")
    A("")

    # ── routing ─────────────────────────────────────────────────────────────
    A("## Routing — how the two environments were mixed\n")
    A("Recovered by replaying the logged atlas calls against the local atlas, "
      "which is deterministic, so these are the bytes the agent actually saw. "
      "Bucket definitions and the caveat that they are heuristic: `routing.py`.\n")
    A("| qid | arm | opened with | atlas calls | web calls | atlas chars | "
      "web chars | coverage | verification | opening |")
    A("|---|---|---|---:|---:|---:|---:|---:|---:|---:|")
    for qid in qids:
        for a in ("hybrid_directed", "hybrid_free"):
            r = route.get((qid, a))
            if not r:
                continue
            b = collections.Counter(w["bucket"] for w in r["web_calls"])
            A(f"| {qid} | `{a}` | `{r['first_tool']}` | {r['n_atlas']} | "
              f"{r['n_web']} | {r['atlas_chars']:,} | {r['web_chars']:,} | "
              f"{b['COVERAGE']} | {b['VERIFICATION']} | {b['OPENING']} |")
    A("")
    A("Every web query, verbatim, with what the atlas had already surfaced when "
      "it was issued: `python routing.py`.\n")

    # ── per question ────────────────────────────────────────────────────────
    for qid in qids:
        runs = sorted(by_q[qid], key=lambda r: r.get("run", 0))
        inc_arm = runs[0].get("incumbent_arm", "?")
        A(f"---\n\n## {qid} — {runs[0].get('family','')}\n")
        A(f"> {runs[0].get('question','')}\n")
        A(f"Incumbent: **{inc_arm}** (the three-arm winner on this question).\n")
        A("| | " + " | ".join(f"{a.replace('hybrid_','')}" for a in ROLES) + " |")
        A("|---|" + "---|" * len(ROLES))
        for ax in AXES:
            cells = []
            for a in ROLES:
                vals = [r[f"{a}_{ax}"] for r in runs]
                cells.append(f"{fmt(mean(vals),1)}  <sub>{'/'.join(str(v) for v in vals)}</sub>")
            A(f"| {ax} | " + " | ".join(cells) + " |")
        A(f"| winner | " + " | ".join(
            f"{sum(1 for r in runs if r['best_answer'] == a)}/{len(runs)}"
            for a in ROLES) + " |")
        A("")
        for a in ROLES:
            row = arow.get((qid, a)) if a != "incumbent" else parent.get((qid, inc_arm))
            answer = (row or {}).get("answer") or {}
            A(f"### {LABEL[a]}\n")
            r = route.get((qid, a))
            if r:
                A(f"*{r['n_atlas']} atlas call(s), {r['n_web']} web call(s), "
                  f"{r['payload_chars']:,} chars, {fmt(r['cost_usd'],3)} USD, "
                  f"{r['seconds']}s — opened with `{r['first_tool']}`*\n")
                if r["sequence"]:
                    A(f"`{' -> '.join(r['sequence'])}`\n")
            A(str(answer.get("answer", "")).strip() + "\n")
            A(f"**Papers named ({len(answer.get('papers_named') or [])}):** "
              + ("; ".join(answer.get("papers_named") or []) or "—") + "  ")
            A(f"**Confidence:** {answer.get('confidence','—')}  ")
            A(f"**Stated limits:** {answer.get('limits','—')}\n")
            for r_ in runs:
                flags = [f for f in ("fabricated", "hedged", "overclaimed")
                         if r_.get(f"{a}_{f}")]
                A(f"> *run {r_.get('run',0)}* ({r_[f'{a}_groundedness']}/"
                  f"{r_[f'{a}_correctness']}/{r_[f'{a}_usefulness']}"
                  + (f", {', '.join(flags)}" if flags else "")
                  + f"): {r_[f'{a}_reason']}\n")

    # ── costs ───────────────────────────────────────────────────────────────
    A("---\n\n## Costs\n")
    gen = sum(r.get("total_cost_usd") or 0 for r in ans)
    jc = sum(r.get("total_cost_usd") or 0 for r in jud)
    A("| | units | USD |")
    A("|---|---:|---:|")
    A(f"| generation (hybrid arms only) | {len(ans)} | {gen:.2f} |")
    A(f"| judging | {len(jud)} | {jc:.2f} |")
    A(f"| **total** | | **{gen + jc:.2f}** |")
    A("\n*Incumbent answers were reused from the parent run, not regenerated — "
      "their generation cost is not counted here.*\n")

    out = "\n".join(L) + "\n"
    if args.out == "-":
        print(out)
    else:
        Path(args.out).write_text(out, encoding="utf-8")
        print(f"wrote {args.out}  ({len(out):,} chars)")


if __name__ == "__main__":
    main()
